/** The first paragraph of a Markdown file, as plain text. */
function mdExcerpt(markdown) {
  const body = markdown
    .replace(/^\uFEFF/, '')
    .replace(/^---\r?\n[\s\S]*?\r?\n---[ \t]*(?:\r?\n|$)/, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[ \t]*(?:```|~~~)[^\n]*\n[\s\S]*?^[ \t]*(?:```|~~~)[^\n]*$/gm, '')
    .replace(/^[ \t]{0,3}#{1,6}[ \t]+.*$/gm, '')
    .replace(/^[^\n]+\n[ \t]*={3,}[ \t]*$/gm, '')
    .replace(/^[^\n]+\n[ \t]*-{3,}[ \t]*$/gm, '')
    .replace(/^[ \t]*>\s*\[![A-Z]+\].*$/gm, '');

  for (const block of body.split(/\r?\n[ \t]*\r?\n/)) {
    const lines = block.split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
    if (!lines.length) continue;
    const first = lines[0];
    // Skip blocks that are not prose: lists, tables, HTML and rules.
    if (/^(?:[-*+]|\d+[.)])[ \t]+/.test(first)) continue;
    if (first.startsWith('|') || /^<[a-z!/]/i.test(first)) continue;
    if (/^([-*_])[ \t]*(?:\1[ \t]*){2,}$/.test(first)) continue;
    // Skip blockquotes (alerts, quotes) and rules from excerpts.
    if (/^>/.test(first)) continue;
    if (/^([-*_])[ \t]*(?:\1[ \t]*){2,}$/.test(first)) continue;
    const text = plain(lines.join(' '));
    if (text) return text;
  }
  return '';
}

const ENTITIES = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'", '&nbsp;': ' ' };

/** The first paragraph of an HTML file, as plain text. */
function htmlExcerpt(html) {
  const paragraph = html.match(/<p\b[^>]*>([\s\S]*?)<\/p>/i);
  const text = paragraph
    ? paragraph[1]
    : html
        .replace(/<(script|style|head|nav)[\s\S]*?<\/\1>/gi, ' ')
        .replace(/<[^>]+>/g, '\n');
  const prose = text
    .replace(/<[^>]+>/g, ' ')
    .replace(/&(?:amp|lt|gt|quot|#39|nbsp);/g, (entity) => ENTITIES[entity.toLowerCase()]);
  const flat = plain(prose);
  return flat || '';
}

