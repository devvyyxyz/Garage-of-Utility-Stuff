const escapeHtml = (text) =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const escapeAttr = (text) =>
  escapeHtml(text).replace(/"/g, '&quot;');

function safeUrl(url) {
  const value = url.trim().replace(/"/g, '%22');
  return /^(https?:\/\/|mailto:|tel:|\/|\.{0,2}\/|#|[^:]+$)/i.test(value) ? value : '#';
}

/** Inline Markdown: code, emphasis, strikethrough, images and links. Input must be escaped. */
function inline(text) {
  return text
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[^*])\*([^*\s][^*]*)\*/g, '$1<em>$2</em>')
    .replace(/_([^_]+)_/g, '<em>$1</em>')
    .replace(/~~([^~]+)~~/g, '<del>$1</del>')
    .replace(/!\[([^\]]*)\]\(([^()\s]*(?:\([^()]*\)[^()\s]*)*)\)/g, '<img alt="$1" src="$2" loading="lazy">')
    .replace(/\[([^\]]+)\]\(([^()\s]*(?:\([^()]*\)[^()\s]*)*)\)/g, (_, label, url) => `<a href="${safeUrl(url)}">${label}</a>`);
}

/** Split a GFM table row into trimmed cells. */
function splitRow(line) {
  let row = line.trim();
  if (row.startsWith('|')) row = row.slice(1);
  if (row.endsWith('|')) row = row.slice(0, -1);
  return row.split('|').map((cell) => cell.trim());
}

const TABLE_DIVIDER = /^\s*\|?\s*:?-{2,}:?\s*(?:\|\s*:?-{2,}:?\s*)+\|?\s*$/;

/** Strip HTML comments from raw markdown so they are not rendered. */
function stripComments(markdown) {
  return markdown.replace(/<!--[\s\S]*?-->/g, '');
}

/** Block-level Markdown. Supports headings, lists, quotes, rules, code and paragraphs. */
export function mdToHtml(markdown) {
  const lines = stripComments(markdown).replace(/\r\n?/g, '\n').split('\n');
  const out = [];
  let paragraph = [];
  let listTag = null;
  let listIndex = -1;

  const flushParagraph = () => {
    if (paragraph.length) {
      out.push(`<p>${inline(escapeHtml(paragraph.join(' ')))}</p>`);
      paragraph = [];
    }
  };
  const flushList = () => {
    if (listTag) {
      out.push(`</${listTag}>`);
      listTag = null;
    }
  };
  const flush = () => {
    flushParagraph();
    flushList();
  };

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trimEnd();
    const trimmed = line.trim();

    const fence = trimmed.match(/^(```|~~~)\s*([\w-]*)\s*$/);
    if (fence) {
      flush();
      const closing = new RegExp(`^\\s*${fence[1]}\\s*$`);
      const code = [];
      i++;
      while (i < lines.length && !closing.test(lines[i])) code.push(lines[i++]);
      const lang = fence[2] ? ` class="language-${escapeAttr(fence[2])}"` : '';
      out.push(`<pre><code${lang}>${escapeHtml(code.join('\n'))}</code></pre>`);
      continue;
    }

    if (!trimmed) {
      flush();
      continue;
    }

    // GFM tables: a header row followed by a |---|---| divider.
    if (trimmed.includes('|') && i + 1 < lines.length && TABLE_DIVIDER.test(lines[i + 1])) {
      flush();
      const header = splitRow(trimmed);
      const aligns = splitRow(lines[i + 1]).map((cell) => {
        const left = cell.startsWith(':');
        const right = cell.endsWith(':');
        return left && right ? 'center' : right ? 'right' : left ? 'left' : '';
      });
      const cell = (tag, text, index) => {
        const align = aligns[index] ? ` style="text-align:${aligns[index]}"` : '';
        return `<${tag}${align}>${inline(escapeHtml(text))}</${tag}>`;
      };

      i += 2;
      const rows = [];
      while (i < lines.length && lines[i].trim() && lines[i].includes('|')) {
        rows.push(splitRow(lines[i]));
        i++;
      }
      i--;

      out.push('<table>');
      out.push('<thead>');
      out.push(`<tr>${header.map((text, n) => cell('th', text, n)).join('')}</tr>`);
      out.push('</thead>');
      out.push('<tbody>');
      for (const row of rows) {
        out.push(`<tr>${row.map((text, n) => cell('td', text, n)).join('')}</tr>`);
      }
      out.push('</tbody>');
      out.push('</table>');
      continue;
    }

    const heading = trimmed.match(/^(#{1,6})\s+(.*)$/);
    if (heading) {
      flush();
      const level = heading[1].length;
      out.push(`<h${level}>${inline(escapeHtml(heading[2].replace(/\s+#+\s*$/, '')))}</h${level}>`);
      continue;
    }

    if (/^(?:-{3,}|\*{3,}|_{3,})$/.test(trimmed)) {
      flush();
      out.push('<hr>');
      continue;
    }

    if (/^>\s?/.test(trimmed)) {
      flush();
      const quoted = [];
      while (i < lines.length && /^\s*>\s?/.test(lines[i])) {
        quoted.push(lines[i].replace(/^\s*>\s?/, ''));
        i++;
      }
      i--;
      const alertMatch = quoted[0]?.match(/^\[!(\w+)\]\s*(.*)$/);
      if (alertMatch) {
        const type = alertMatch[1].toLowerCase();
        const rest = alertMatch[2];
        const valid = ['note', 'tip', 'important', 'warning', 'caution'];
        if (valid.includes(type)) {
          const title = type.charAt(0).toUpperCase() + type.slice(1);
          const content = rest ? `\n${rest}\n${quoted.slice(1).join('\n')}` : quoted.slice(1).join('\n');
          out.push(`<div class="markdown-alert markdown-alert-${type}">\n  <p class="markdown-alert-title">${title}</p>\n  ${mdToHtml(content)}\n</div>`);
          continue;
        }
      }
      out.push(`<blockquote>${mdToHtml(quoted.join('\n'))}</blockquote>`);
      continue;
    }

    // Setext headings (text underlined with === or ---).
    if (paragraph.length === 1 && /^(?:={3,}|-{2,})$/.test(trimmed)) {
      const level = trimmed[0] === '=' ? 1 : 2;
      const text = inline(escapeHtml(paragraph[0]));
      paragraph = [];
      out.push(`<h${level}>${text}</h${level}>`);
      continue;
    }

    const unordered = trimmed.match(/^[-*+]\s+(.*)$/);
    const ordered = trimmed.match(/^\d+[.)]\s+(.*)$/);
    if (unordered || ordered) {
      flushParagraph();
      const tag = unordered ? 'ul' : 'ol';
      if (listTag && listTag !== tag) flushList();
      if (!listTag) {
        out.push(`<${tag}>`);
        listTag = tag;
        listIndex = out.length - 1;
      }
      const text = (unordered || ordered)[1];
      const task = unordered && text.match(/^\[([ xX])\]\s+(.*)$/);
      if (task) {
        out[listIndex] = `<${tag} class="contains-task-list">`;
        out.push(`<li class="task-list-item"><input type="checkbox" disabled${task[1] === ' ' ? '' : ' checked'}> ${inline(escapeHtml(task[2]))}</li>`);
        continue;
      }
      out.push(`<li>${inline(escapeHtml(text))}</li>`);
      continue;
    }

    flushList();
    paragraph.push(trimmed);
  }
  flush();
  return out.join('\n');
}

/* -------------------------------------------------------------------- helpers */

function prettifyName(file) {
  const name = basename(file, extname(file)).replace(/[-_]+/g, ' ').trim();
  return name
    .split(' ')
    .map((word) => {
      if (!word) return word;
      if (word === word.toUpperCase() && word.length > 1) {
        return word[0] + word.slice(1).toLowerCase();
      }
      return word[0].toUpperCase() + word.slice(1);
    })
    .join(' ');
}

/** Human label for a file or folder name: separators become spaces, case is kept. */
const cleanedName = (name) => {
  const spaced = name.replace(/[-_]+/g, ' ').replace(/\s+/g, ' ').trim();
  if (!spaced) return spaced;
  // All-caps names (e.g. CODE_OF_CONDUCT) are acronyms: keep them uppercase.
  if (spaced === spaced.toUpperCase() && spaced.length > 1) return spaced;
  return spaced;
};

function plain(text) {
  return text
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/\[!\w+\]/g, ' ')
    .replace(/`([^`]*)`/g, '$1')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/[*_#>~|]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function mdTitle(markdown, file) {
  const heading = markdown.match(/^\s{0,3}#\s+(.+?)\s*#*\s*$/m);
  if (heading) return plain(heading[1]);
  const setext = markdown.match(/^(.+)\n={3,}\s*$/m);
  if (setext) return plain(setext[1]);
  return cleanedName(basename(file, extname(file)));
}

function truncate(text, limit) {
  const clean = text.replace(/\s+/g, ' ').trim();
  if (clean.length <= limit) return clean;
  const cut = clean.slice(0, limit);
  const space = cut.lastIndexOf(' ');
  return `${(space > limit * 0.6 ? cut.slice(0, space) : cut).replace(/[,;:.]$/, '')}\u2026`;
}

