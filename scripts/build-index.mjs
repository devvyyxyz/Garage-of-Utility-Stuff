async function downloadIcon(name, baseUrl) {
  const file = join(ICON_DIR, `${name}.svg`);
  const cached = await readFile(file, 'utf8').catch(() => '');
  if (cached) return cached;
  try {
    const response = await fetch(`${baseUrl}${name}.svg`, { signal: AbortSignal.timeout(15000) });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const svg = await response.text();
    if (!svg.includes('<svg')) throw new Error('unexpected icon contents');
    await mkdir(ICON_DIR, { recursive: true });
    await writeFile(file, svg, 'utf8');
    return svg;
  } catch (error) {
    console.warn(`warning: icon "${name}" unavailable (${error.message})`);
    return '';
  }
}

/** Keep only the icons the current pages use on disk. */
async function pruneIcons(needed) {
  const entries = await readdir(ICON_DIR).catch(() => []);
  for (const entry of entries) {
    if (entry.endsWith('.svg') && !needed.has(entry.slice(0, -4))) {
      await unlink(join(ICON_DIR, entry)).catch(() => {});
    }
  }
}

/** Inline the icon so it inherits the surrounding text colour. */
function inlineIcon(svg, className = 'icon') {
  const attributes =
    `class="${className}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ` +
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"';
  if (!svg) return `<svg ${attributes}></svg>`;
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  return `<svg ${attributes}>${inner.trim()}</svg>`;
}

const execFileAsync = promisify(execFile);

/** Read the latest git commit author and date for a file, or empty when git has no record. */
async function gitInfo(source) {
  try {
    const { stdout } = await execFileAsync('git', ['-C', ROOT, 'log', '-1', '--format=%an%x1f%cs', '--', source], {
      timeout: 5000,
    });
    const [author, dateISO] = stdout.trim().split('\x1f');
    if (author && dateISO) return { author, dateISO };
  } catch {
    // git missing, file not committed, or not a repository: fall through.
  }
  return { author: '', dateISO: '' };
}

/** Strip markup from Markdown so the remaining words can be counted. */
function markdownProse(raw) {
  const stripped = raw
    .replace(/^\uFEFF/, '')
    .replace(/^---\r?\n[\s\S]*?\r?\n---[ \t]*(?:\r?\n|$)/, '')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/~~~[\s\S]*?~~~/g, ' ')
    .replace(/^[ \t]{0,3}#{1,6}[ \t]+[^\n]*$/gm, '')
    .replace(/^[^\n]+\n[ \t]*={3,}[ \t]*$/gm, '')
    .replace(/^[^\n]+\n[ \t]*-{3,}[ \t]*$/gm, '');
  return plain(
    stripped
      .replace(/<[^>]+>/g, ' ')
      .replace(/&(?:amp|lt|gt|quot|#39|nbsp);/g, (entity) => ENTITIES[entity.toLowerCase()] || entity),
  );
}

/** Estimated reading time from word count, or "Unknown" for empty text. */
function estimateReadTime(raw) {
  const words = markdownProse(raw).split(/\s+/).filter(Boolean).length;
  if (words === 0) return 'Unknown';
  const minutes = Math.max(1, Math.ceil(words / 200));
  return `${minutes} min${minutes === 1 ? '' : 's'} read`;
}

/** Format a git date (YYYY-MM-DD) as a short human date, or "Unknown". */
function formatDate(iso) {
  if (!iso) return 'Unknown';
  const date = new Date(`${iso}T00:00:00`);
  if (Number.isNaN(date.getTime())) return 'Unknown';
  return date.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
}

/** Build the byline shown under each page title. */
async function pageMeta(source, raw) {
  const info = await gitInfo(source);
  const author = info.author || 'Unknown';
  const updated = formatDate(info.dateISO);
  const read = estimateReadTime(raw);
  return `<p class="page-meta">By <strong>${escapeHtml(author)}</strong> &middot; Updated ${escapeHtml(updated)} &middot; ${escapeHtml(read)}</p>`;
}

/**
 * Downloads GitHub's Markdown stylesheet next to the site, keeping the existing
 * copy when the network is unavailable so local builds stay reproducible.
 */
async function ensureGithubCss() {
  const existing = await readFile(GITHUB_CSS_FILE, 'utf8').catch(() => '');
  try {
    await mkdir(CACHE_DIR, { recursive: true });
    const response = await fetch(GITHUB_CSS_URL, { signal: AbortSignal.timeout(20000) });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const css = await response.text();
    if (!css.includes('.markdown-body')) throw new Error('unexpected stylesheet contents');
    const next = GITHUB_CSS_HEADER + css;
    if (next !== existing) {
      await writeFile(GITHUB_CSS_FILE, next, 'utf8');
      console.log('github-markdown.css: downloaded');
    }
    return true;
  } catch (error) {
    if (existing) {
      console.warn(`warning: using cached github-markdown.css (${error.message})`);
      return true;
    }
    console.warn(`warning: github-markdown.css unavailable (${error.message}); pages use site.css only`);
    return false;
  }
}

