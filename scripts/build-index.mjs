/** Remove a trailing # comment, ignoring # inside quoted strings. */
function stripComment(line) {
  let single = false;
  let double = false;
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    if (char === "'" && !double) single = !single;
    else if (char === '"' && !single) double = !double;
    else if (char === '#' && !single && !double && (i === 0 || /\s/.test(line[i - 1]))) return line.slice(0, i);
  }
  return line;
}

/** Split an inline list on commas that are not inside quotes. */
function splitInline(text) {
  const parts = [];
  let current = '';
  let single = false;
  let double = false;
  for (const char of text) {
    if (char === "'" && !double) single = !single;
    else if (char === '"' && !single) double = !double;
    if (char === ',' && !single && !double) {
      parts.push(current);
      current = '';
      continue;
    }
    current += char;
  }
  parts.push(current);
  return parts.map((part) => part.trim()).filter(Boolean);
}

function parseScalar(value) {
  const text = value.trim();
  if (text.startsWith('[') && text.endsWith(']')) return splitInline(text.slice(1, -1)).map(parseScalar);
  if (text.length > 1 && (text[0] === '"' || text[0] === "'") && text.at(-1) === text[0]) return text.slice(1, -1);
  if (text === 'true') return true;
  if (text === 'false') return false;
  if (text === 'null' || text === '~') return null;
  return text;
}

const isMappingStart = (text) => /^[^:]+:(\s|$)/.test(text);

function splitKeyValue(text) {
  const index = text.indexOf(':');
  return { key: text.slice(0, index).trim(), value: text.slice(index + 1).trim() };
}

function parseMapping(lines, start, indent) {
  const result = {};
  let i = start;
  while (i < lines.length) {
    const line = lines[i];
    if (line.indent < indent) break;
    if (line.indent > indent) throw new Error(`line ${line.line}: unexpected indentation`);
    if (line.text.startsWith('-')) break;
    const { key, value } = splitKeyValue(line.text);
    if (!key) throw new Error(`line ${line.line}: expected "key: value"`);
    i++;
    if (value) {
      result[key] = parseScalar(value);
    } else if (i < lines.length && lines[i].indent > indent) {
      const [nested, next] = parseBlock(lines, i, lines[i].indent);
      result[key] = nested;
      i = next;
    } else {
      result[key] = null;
    }
  }
  return [result, i];
}

function parseSequence(lines, start, indent) {
  const result = [];
  let i = start;
  while (i < lines.length) {
    const line = lines[i];
    if (line.indent < indent) break;
    if (line.indent > indent) throw new Error(`line ${line.line}: unexpected indentation`);
    if (!line.text.startsWith('-')) break;
    const rest = line.text.slice(1).trim();
    i++;

    if (!rest) {
      if (i < lines.length && lines[i].indent > indent) {
        const [nested, next] = parseBlock(lines, i, lines[i].indent);
        result.push(nested);
        i = next;
      } else {
        result.push(null);
      }
      continue;
    }

    if (isMappingStart(rest)) {
      const continuationIndent = i < lines.length && lines[i].indent > indent ? lines[i].indent : indent + 2;
      const itemLines = [{ indent: continuationIndent, text: rest, line: line.line }];
      while (i < lines.length && lines[i].indent > indent) {
        itemLines.push(lines[i]);
        i++;
      }
      const [mapping] = parseMapping(itemLines, 0, continuationIndent);
      result.push(mapping);
      continue;
    }

    result.push(parseScalar(rest));
  }
  return [result, i];
}

function parseBlock(lines, start, indent) {
  return lines[start].text.startsWith('-')
    ? parseSequence(lines, start, indent)
    : parseMapping(lines, start, indent);
}

/** Minimal YAML parser for the shapes docs-config.yml uses. */
function parseYaml(text) {
  const lines = [];
  text.replace(/\r\n?/g, '\n').split('\n').forEach((raw, index) => {
    if (/^ *\t/.test(raw)) throw new Error(`line ${index + 1}: tabs are not supported for indentation`);
    const line = stripComment(raw);
    if (!line.trim()) return;
    lines.push({ indent: line.match(/^ */)[0].length, text: line.trim(), line: index + 1 });
  });
  if (!lines.length) return {};
  return parseBlock(lines, 0, lines[0].indent)[0];
}

const normalizePath = (path) => path.replace(/\\/g, '/').replace(/^\.\//, '').trim();

/** Read docs-config.yml and fill in defaults; returns { config, warnings }. */
async function loadConfig() {
  const warnings = [];
  const config = {
    title: TITLE,
    home: 'README.MD',
    icons: { set: 'lucide', version: ICON_VERSION, default: DEFAULT_ICON },
    pages: [],
    groups: [],
  };

  let raw = '';
  try {
    raw = await readFile(CONFIG_FILE, 'utf8');
  } catch {
    warnings.push('docs-config.yml not found - only docs/ pages are listed');
    return { config, warnings };
  }

  let parsed;
  try {
    parsed = parseYaml(raw) || {};
  } catch (error) {
    warnings.push(`docs-config.yml: ${error.message}`);
    return { config, warnings };
  }

  if (parsed.site && typeof parsed.site.title === 'string') config.title = parsed.site.title;
  if (parsed.site && typeof parsed.site.home === 'string') config.home = normalizePath(parsed.site.home);
  if (parsed.icons && typeof parsed.icons === 'object') {
    if (typeof parsed.icons.set === 'string' && parsed.icons.set !== 'lucide') {
      warnings.push(`docs-config.yml: icon set "${parsed.icons.set}" is not supported; using lucide`);
    }
    if (typeof parsed.icons.version === 'string' || typeof parsed.icons.version === 'number') {
      config.icons.version = String(parsed.icons.version);
    }
    if (typeof parsed.icons.default === 'string') config.icons.default = parsed.icons.default;
  }

  for (const entry of Array.isArray(parsed.pages) ? parsed.pages : []) {
    if (typeof entry === 'string') {
      config.pages.push({ path: normalizePath(entry), icon: '' });
    } else if (entry && typeof entry === 'object' && typeof entry.path === 'string') {
      config.pages.push({ path: normalizePath(entry.path), icon: typeof entry.icon === 'string' ? entry.icon : '' });
    } else {
      warnings.push('docs-config.yml: every entry in "pages" needs a path');
    }
  }

  for (const group of Array.isArray(parsed.groups) ? parsed.groups : []) {
    if (!group || typeof group !== 'object') {
      warnings.push('docs-config.yml: every entry in "groups" needs a title');
      continue;
    }
    const folderEntries = [
      ...(typeof group.folder === 'string' ? [group.folder] : []),
      ...(Array.isArray(group.folders) ? group.folders : []),
    ];
    const folders = [];
    for (const folder of folderEntries) {
      if (typeof folder === 'string') {
        folders.push(normalizePath(folder));
      } else if (folder && typeof folder === 'object' && typeof folder.path === 'string') {
        folders.push(normalizePath(folder.path));
      } else {
        warnings.push(`docs-config.yml: group "${group.title}" has a folder entry without a path`);
      }
    }
    config.groups.push({
      title: typeof group.title === 'string' ? group.title : '',
      icon: typeof group.icon === 'string' ? group.icon : '',
      pages: (Array.isArray(group.pages) ? group.pages : []).filter((page) => typeof page === 'string').map(normalizePath),
      folders,
    });
  }

  return { config, warnings };
}

