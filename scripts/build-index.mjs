#!/usr/bin/env node
/**
 * Builds the site index for docs/.
 *
 * 1. Converts every Markdown file in docs/ to a sibling .html file
 *    (a small, dependency-free subset of GitHub-flavored Markdown).
 * 2. Walks docs/ and writes docs/index.html: a searchable card index of
 *    every page, grouped by folder.
 *
 * Run with: node scripts/build-index.mjs
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, extname, basename, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DOCS = join(ROOT, 'docs');
const TEMPLATE = join(ROOT, 'scripts', 'index-template.html');
const TITLE = 'Garage of Utility Stuff';
const MARKER = '<!-- Generated by scripts/build-index.mjs';
const HTML_EXT = new Set(['.html', '.htm']);
const IGNORED = new Set(['node_modules', 'index.html']);
const EXCLUDE = /(^|[\\/])\.|\.(jpg|jpeg|png|gif|webp|svg|ico|pdf|zip|css|js|json|yml|yaml|txt|xml|woff2?)$/i;

/* ------------------------------------------------------------------ markdown */

const escapeHtml = (text) =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const escapeAttr = (text) =>
  escapeHtml(text).replace(/"/g, '&quot;');

function safeUrl(url) {
  const value = url.trim().replace(/"/g, '%22');
  return /^(https?:\/\/|mailto:|tel:|\/|\.{0,2}\/|#|[^:]+$)/i.test(value) ? value : '#';
}

/** Inline Markdown: code, emphasis, images and links. Input must be escaped. */
function inline(text) {
  return text
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[^*])\*([^*\s][^*]*)\*/g, '$1<em>$2</em>')
    .replace(/!\[([^\]]*)\]\(([^()\s]*(?:\([^()]*\)[^()\s]*)*)\)/g, '<img alt="$1" src="$2" loading="lazy">')
    .replace(/\[([^\]]+)\]\(([^()\s]*(?:\([^()]*\)[^()\s]*)*)\)/g, (_, label, url) => `<a href="${safeUrl(url)}">${label}</a>`);
}

/** Block-level Markdown. Supports headings, lists, quotes, rules, code and paragraphs. */
export function mdToHtml(markdown) {
  const lines = markdown.replace(/\r\n?/g, '\n').split('\n');
  const out = [];
  let paragraph = [];
  let listTag = null;

  const flushParagraph = () => {
    if (paragraph.length) {
      out.push(`<p>${inline(escapeHtml(paragraph.join(' ')))}</p>`);
      paragraph = [];
    }
  };
  const flushList = () => {
    if (listTag) {
      out.push(`</${listTag}>`);
      listTag = null;
    }
  };
  const flush = () => {
    flushParagraph();
    flushList();
  };

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trimEnd();
    const trimmed = line.trim();

    const fence = trimmed.match(/^(```|~~~)\s*([\w-]*)\s*$/);
    if (fence) {
      flush();
      const closing = new RegExp(`^\\s*${fence[1]}\\s*$`);
      const code = [];
      i++;
      while (i < lines.length && !closing.test(lines[i])) code.push(lines[i++]);
      const lang = fence[2] ? ` class="language-${escapeAttr(fence[2])}"` : '';
      out.push(`<pre><code${lang}>${escapeHtml(code.join('\n'))}</code></pre>`);
      continue;
    }

    if (!trimmed) {
      flush();
      continue;
    }

    const heading = trimmed.match(/^(#{1,6})\s+(.*)$/);
    if (heading) {
      flush();
      const level = heading[1].length;
      out.push(`<h${level}>${inline(escapeHtml(heading[2].replace(/\s+#+\s*$/, '')))}</h${level}>`);
      continue;
    }

    if (/^(?:-{3,}|\*{3,}|_{3,})$/.test(trimmed)) {
      flush();
      out.push('<hr>');
      continue;
    }

    if (/^>\s?/.test(trimmed)) {
      flush();
      const quoted = [];
      while (i < lines.length && /^\s*>\s?/.test(lines[i])) {
        quoted.push(lines[i].replace(/^\s*>\s?/, ''));
        i++;
      }
      i--;
      out.push(`<blockquote>${mdToHtml(quoted.join('\n'))}</blockquote>`);
      continue;
    }

    // Setext headings (text underlined with === or ---).
    if (paragraph.length === 1 && /^(?:={3,}|-{2,})$/.test(trimmed)) {
      const level = trimmed[0] === '=' ? 1 : 2;
      const text = inline(escapeHtml(paragraph[0]));
      paragraph = [];
      out.push(`<h${level}>${text}</h${level}>`);
      continue;
    }

    const unordered = trimmed.match(/^[-*+]\s+(.*)$/);
    const ordered = trimmed.match(/^\d+[.)]\s+(.*)$/);
    if (unordered || ordered) {
      flushParagraph();
      const tag = unordered ? 'ul' : 'ol';
      if (listTag && listTag !== tag) flushList();
      if (!listTag) {
        out.push(`<${tag}>`);
        listTag = tag;
      }
      out.push(`<li>${inline(escapeHtml((unordered || ordered)[1]))}</li>`);
      continue;
    }

    flushList();
    paragraph.push(trimmed);
  }
  flush();
  return out.join('\n');
}

/* -------------------------------------------------------------------- helpers */

function prettifyName(file) {
  const name = basename(file, extname(file)).replace(/[-_]+/g, ' ').trim();
  return name
    .split(' ')
    .map((word) => {
      if (!word) return word;
      if (word === word.toUpperCase() && word.length > 1) {
        return word[0] + word.slice(1).toLowerCase();
      }
      return word[0].toUpperCase() + word.slice(1);
    })
    .join(' ');
}

function plain(text) {
  return text
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/`([^`]*)`/g, '$1')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/[*_#>~]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function truncate(text, limit = 160) {
  if (text.length <= limit) return text;
  const cut = text.slice(0, limit);
  const space = cut.lastIndexOf(' ');
  return `${(space > 80 ? cut.slice(0, space) : cut).replace(/[,;:.]$/, '')}\u2026`;
}

function mdTitle(markdown, file) {
  const heading = markdown.match(/^\s{0,3}#\s+(.+?)\s*#*\s*$/m);
  if (heading) return plain(heading[1]);
  const setext = markdown.match(/^(.+)\n={3,}\s*$/m);
  if (setext) return plain(setext[1]);
  return prettifyName(file);
}

function mdDescription(markdown) {
  const body = markdown
    .replace(/^\s{0,3}#{1,6}\s+.*$/gm, '')
    .replace(/```[\s\S]*?```/g, '')
    .replace(/^\s*>\s?/gm, '');
  const block = body.split(/\n\s*\n/).map(plain).find((text) => text.length > 0);
  return block ? truncate(block) : '';
}

function htmlMeta(html) {
  const title = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  const description = html.match(/<meta[^>]+name=["']description["'][^>]*content=["']([^"']*)["']/i);
  const heading = html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i);
  const text = title || heading;
  return {
    title: text ? truncate(plain(text[1].replace(/<[^>]+>/g, ' ')), 90) : '',
    description: description ? truncate(plain(description[1])) : '',
  };
}

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (IGNORED.has(entry.name)) continue;
      files.push(...(await walk(path)));
    } else if (!IGNORED.has(entry.name) && !EXCLUDE.test(entry.name)) {
      files.push(path);
    }
  }
  return files;
}

const toUrl = (path) => relative(DOCS, path).split(sep).map(encodeURIComponent).join('/');

const sectionOf = (path) => {
  const dir = relative(DOCS, dirname(path));
  return dir && dir !== '.' ? dir.split(sep)[0] : '';
};

const sectionLabel = (name) => (name ? prettifyName(name) : 'Pages');

/* ----------------------------------------------------------------------- build */

async function build() {
  const files = await walk(DOCS);
  const pages = [];
  const warnings = [];

  for (const file of files) {
    const ext = extname(file).toLowerCase();

    if (ext === '.md' || ext === '.markdown') {
      const raw = await readFile(file, 'utf8');
      const target = file.replace(/\.(md|markdown)$/i, '.html');
      const title = mdTitle(raw, file);
      const html = [
        '<!doctype html>',
        '<html lang="en">',
        '<head>',
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        `<title>${escapeHtml(title)} \u2014 ${TITLE}</title>`,
        `${MARKER}, generated from ${escapeHtml(basename(file))} \u2014 edits are overwritten. -->`,
        '<style>',
        'body{max-width:46rem;margin:0 auto;padding:3rem 1.25rem 5rem;background:#0a0d12;color:#e8eef7;',
        'font:17px/1.7 ui-sans-serif,system-ui,-apple-system,"Segoe UI",Roboto,Helvetica,Arial,sans-serif}',
        'a{color:#ffb020}a:hover{color:#ffc44d}',
        'h1,h2,h3,h4{line-height:1.25;letter-spacing:-.01em;margin:2rem 0 .75rem}',
        'h1{font-size:2rem;margin-top:0}',
        'code{font:.9em ui-monospace,SFMono-Regular,Menlo,monospace;background:#16202d;padding:.15em .35em;border-radius:4px}',
        'pre{background:#0f141b;border:1px solid #1f2a38;border-radius:10px;padding:1rem;overflow:auto}',
        'pre code{background:none;padding:0}',
        'blockquote{margin:1rem 0;padding:.25rem 1rem;border-left:3px solid #ffb020;color:#8b9bb0}',
        'hr{border:0;border-top:1px solid #1f2a38;margin:2rem 0}',
        'img{max-width:100%;height:auto}',
        '.back{display:inline-block;margin-bottom:2rem;color:#8b9bb0;text-decoration:none;font-size:.85rem}',
        '.back:hover{color:#ffb020}',
        'nav{display:flex;gap:.5rem;flex-wrap:wrap;margin-top:3rem;padding-top:1rem;border-top:1px solid #1f2a38;font-size:.85rem}',
        '</style>',
        '</head>',
        '<body>',
        '<a class="back" href="./index.html">\u2190 All pages</a>',
        `<main>\n${mdToHtml(raw)}\n</main>`,
        '<nav>',
        `<a href="./index.html">Index</a>`,
        '</nav>',
        '</body>',
        '</html>',
        '',
      ].join('\n');

      await writeFile(target, html, 'utf8');
      pages.push({
        file: target,
        url: toUrl(target),
        title,
        description: mdDescription(raw),
        source: basename(file),
      });
      continue;
    }

    if (HTML_EXT.has(ext) && file !== join(DOCS, 'index.html')) {
      const raw = await readFile(file, 'utf8');
      if (raw.slice(0, 800).includes(MARKER)) continue; // our own generated page
      const meta = htmlMeta(raw);
      pages.push({
        file,
        url: toUrl(file),
        title: meta.title || prettifyName(file),
        description: meta.description,
        source: basename(file),
      });
    }
  }

  if (!pages.length) warnings.push('no pages found in docs/ - the index will be empty');

  pages.sort((a, b) => {
    const section = sectionOf(a.file).localeCompare(sectionOf(b.file));
    return section || a.title.localeCompare(b.title, undefined, { sensitivity: 'base' });
  });

  const groups = new Map();
  for (const page of pages) {
    const name = sectionOf(page.file);
    if (!groups.has(name)) groups.set(name, []);
    groups.get(name).push(page);
  }

  const card = (page) => {
    const search = `${page.title} ${page.description} ${page.url}`.toLowerCase();
    const path = `docs/${page.url}`;
    return [
      `        <a class="card" data-page data-search="${escapeAttr(search)}" href="${escapeAttr(page.url)}">`,
      `          <h3>${escapeHtml(page.title)}</h3>`,
      page.description ? `          <p>${escapeHtml(page.description)}</p>` : '',
      `          <span class="path">${escapeHtml(path)}</span>`,
      '        </a>',
    ].filter(Boolean).join('\n');
  };

  const sections = [...groups.entries()].map(([name, members]) => [
    '    <section class="section" data-section>',
    `      <h2>${escapeHtml(sectionLabel(name))}<span class="count">${members.length}</span></h2>`,
    '      <div class="grid">',
    members.map(card).join('\n'),
    '      </div>',
    '    </section>',
  ].join('\n')).join('\n\n');

  const template = await readFile(TEMPLATE, 'utf8');
  const count = `${pages.length} page${pages.length === 1 ? '' : 's'}`;
  const index = template
    .replaceAll('%TITLE%', `${TITLE} \u2014 Utils`)
    .replaceAll('%HEADING%', TITLE.replace(/^(.*?)\s*\((.*)\)$/, '$1 <span>$2</span>'))
    .replaceAll('%LEDE%', 'Small, self-hosted utilities in one place. Pick a page to get started.')
    .replaceAll('%COUNT%', count)
    .replaceAll('%SECTIONS%', sections || '    <p class="empty">Nothing here yet.</p>')
    .replaceAll('%GENERATED%', `${count} \u00b7 built ${new Date().toISOString().slice(0, 10)}`);

  await writeFile(join(DOCS, 'index.html'), `${MARKER} \u2014 do not edit. -->\n${index}`, 'utf8');

  for (const warning of warnings) console.warn(`warning: ${warning}`);
  console.log(`index: ${pages.length} page(s) across ${groups.size} section(s) -> docs/index.html`);
  return pages;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await build();
}
